"""Shopping cart models.

A customer has at most one *active* cart at a time (enforced by a partial
unique index). Completed carts are retained as ``converted``/``abandoned`` for
analytics, so the constraint never fights history.

Money fields on :class:`CartItem` are stored as **price snapshots** taken when
the item is added. That keeps the cart total stable if an admin edits the
product price mid-session, while :meth:`CartItem.refresh_price` lets the client
(or checkout) deliberately adopt the latest price.
"""

from decimal import Decimal

from django.db import models

from common.models import BaseModel
from common.utils import round_money

ZERO = Decimal("0.00")


class CartStatus(models.TextChoices):
    ACTIVE = "active", "Active"
    CONVERTED = "converted", "Converted to order"
    ABANDONED = "abandoned", "Abandoned"
    MERGED = "merged", "Merged"


class Cart(BaseModel):
    """A shopping cart belonging to one customer."""

    customer = models.ForeignKey(
        "customers.Customer",
        on_delete=models.CASCADE,
        related_name="carts",
        null=True,
        blank=True,
        help_text="Null for a guest basket - it is merged into a real account on login.",
    )
    status = models.CharField(
        max_length=20, choices=CartStatus.choices, default=CartStatus.ACTIVE,
        db_index=True,
    )
    guest_key = models.CharField(
        max_length=64,
        blank=True,
        default="",
        db_index=True,
        help_text=(
            "Anonymous basket identifier generated by the browser. Round 23: a "
            "shopper can fill a cart before signing in; the key is how that "
            "basket is found again, and it is merged away on login."
        ),
    )
    coupon_code = models.CharField(
        max_length=40, blank=True, default="",
        help_text="Coupon the customer has applied to this cart.",
    )
    notes = models.TextField(blank=True, default="")
    converted_order = models.ForeignKey(
        "orders.Order",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="source_carts",
    )
    last_activity_at = models.DateTimeField(auto_now=True, db_index=True)

    class Meta(BaseModel.Meta):
        db_table = "cart_cart"
        verbose_name = "Cart"
        verbose_name_plural = "Carts"
        ordering = ("-created_at",)
        constraints = [
            models.UniqueConstraint(
                fields=["customer"],
                condition=models.Q(status=CartStatus.ACTIVE),
                name="unique_active_cart_per_customer",
            ),
        ]
        indexes = [
            models.Index(fields=["customer", "status"], name="idx_cart_customer_status"),
        ]

    def __str__(self) -> str:
        owner = self.customer_id or f"guest:{self.guest_key or '-'}"
        return f"Cart {self.pk} for customer {owner} [{self.status}]"

    @property
    def is_active(self) -> bool:
        return self.status == CartStatus.ACTIVE

    # --- money ---------------------------------------------------------
    @property
    def subtotal(self) -> Decimal:
        return round_money(sum((item.line_total for item in self.items.all()), ZERO))

    @property
    def mrp_total(self) -> Decimal:
        return round_money(sum((item.line_mrp_total for item in self.items.all()), ZERO))

    @property
    def item_count(self) -> int:
        return self.items.count()

    @property
    def total_quantity(self) -> int:
        return sum(item.quantity for item in self.items.all())

    @property
    def savings(self) -> Decimal:
        return max(ZERO, round_money(self.mrp_total - self.subtotal))

    def recalculate(self) -> "Cart":
        """Touch the cart so ``last_activity_at`` refreshes. Totals are derived."""
        self.save(update_fields=["last_activity_at", "updated_at"])
        return self


class CartItem(BaseModel):
    """One product line in a cart."""

    cart = models.ForeignKey(Cart, on_delete=models.CASCADE, related_name="items")
    product = models.ForeignKey(
        "catalog.Product", on_delete=models.CASCADE, related_name="cart_items"
    )
    quantity = models.PositiveIntegerField(default=1)
    unit_price = models.DecimalField(
        max_digits=12, decimal_places=2,
        help_text="Price snapshot captured when the item was added.",
    )
    unit_mrp = models.DecimalField(
        max_digits=12, decimal_places=2,
        help_text="MRP snapshot captured when the item was added.",
    )
    product_name_snapshot = models.CharField(max_length=200, blank=True, default="")
    notes = models.CharField(max_length=255, blank=True, default="")
    added_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta(BaseModel.Meta):
        db_table = "cart_item"
        verbose_name = "Cart item"
        verbose_name_plural = "Cart items"
        ordering = ("added_at",)
        constraints = [
            models.UniqueConstraint(
                fields=["cart", "product"], name="unique_cart_product"
            ),
            models.CheckConstraint(
                condition=models.Q(quantity__gt=0), name="cart_item_quantity_positive"
            ),
            models.CheckConstraint(
                condition=models.Q(quantity__lte=999), name="cart_item_quantity_sane"
            ),
            models.CheckConstraint(
                condition=models.Q(unit_price__gte=0), name="cart_item_price_non_negative"
            ),
        ]
        indexes = [
            models.Index(fields=["cart", "added_at"], name="idx_cartitem_cart_added"),
        ]

    def __str__(self) -> str:
        return f"{self.quantity} x {self.product_name_snapshot or self.product_id}"

    @property
    def line_total(self) -> Decimal:
        return round_money(self.unit_price * self.quantity)

    @property
    def line_mrp_total(self) -> Decimal:
        return round_money(self.unit_mrp * self.quantity)

    @property
    def line_savings(self) -> Decimal:
        return max(ZERO, round_money(self.line_mrp_total - self.line_total))

    @property
    def price_changed(self) -> bool:
        return self.product.selling_price != self.unit_price

    def refresh_price(self, save: bool = True) -> "CartItem":
        """Adopt the product's current price and MRP."""
        self.unit_price = self.product.selling_price
        self.unit_mrp = self.product.mrp
        self.product_name_snapshot = self.product.name
        if save:
            self.save(update_fields=["unit_price", "unit_mrp", "product_name_snapshot",
                                     "updated_at"])
        return self
